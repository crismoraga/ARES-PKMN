"""Generate the IEEE report assets (numbers, tables, figures) from the E1/E2 protocol outputs.

Nothing in ``informe/`` is typed by hand from results: run this after the protocols finish::

    python -m ares_u.battle.paired evaluate --run artifacts/ares_u/battle/final
    python -m scripts.ares_u_battle summarize --run artifacts/ares_u/battle/final   (figures)
    python -m scripts.ares_u_report_assets

Writes ``informe/generated/{numbers.tex, tab_e1.tex, tab_hyp.tex, tab_e2.tex}`` and copies the figures
into ``informe/figs``.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METHOD_NAMES = {"bc": "BC (imitación)", "ppo": "PPO-Transformer", "bc_ppo": "BC$\\to$PPO",
                "ppo_ids": "PPO + IDs (ablación)", "dqn": "DQN-MLP (curso)"}
BASELINE_NAMES = {"greedy": "Greedy (heurística)", "prior": "Prior ARES (heurística)", "random": "Aleatorio"}
SPLIT_NAMES = {"gen1_train": "Gen1", "gen1_heldout": "Gen1-H", "gen2": "Gen2$^\\ast$", "gen3": "Gen3$^\\ast$"}
NAV_METHODS = {"random": "Aleatorio", "scratch": "Desde cero", "transfer": "Transferencia FR$\\to$EM",
               "zero_shot": "Zero-shot (política FR)"}


def macro_name(*parts: str) -> str:
    words = re.split(r"[^A-Za-z0-9]+", " ".join(parts))
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six",
              "7": "Seven", "8": "Eight", "9": "Nine"}
    name = "".join(word[:1].upper() + word[1:] for word in words if word)
    return "".join(digits.get(char, char) for char in name)


def fmt_p(value: float) -> str:
    return "$<10^{-4}$" if value < 1e-4 else f"{value:.3f}" if value >= 1e-3 else f"{value:.1e}"


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = ["% Generated by scripts/ares_u_report_assets.py -- do not edit by hand."]

    def add(self, name: str, value: str) -> None:
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def e1_assets(run: Path, out: Path, figs: Path, macros: Macros) -> None:
    paired = json.loads((run / "paired.json").read_text(encoding="utf-8"))
    splits = [s for s in ("gen1_train", "gen1_heldout", "gen2", "gen3") if s in paired["splits"]]
    scores = paired["scores"]
    macros.add("EoneBattles", str(paired.get("battles")))
    seeds = max((entry["seeds"] for m in scores.values() for s in m.values() for entry in s.values()), default=0)
    macros.add("EoneSeeds", str(seeds))
    for method, by_split in scores.items():
        for split, by_opp in by_split.items():
            for opponent, entry in by_opp.items():
                base = macro_name("Eone", method, opponent, split)
                macros.add(base, f"{entry['mean']:.3f}")
                macros.add(base + "Lo", f"{entry['pair_ci'][0]:.3f}")
                macros.add(base + "Hi", f"{entry['pair_ci'][1]:.3f}")
    for row, by_split in paired.get("baselines", {}).items():
        for split, by_opp in by_split.items():
            for opponent, entry in by_opp.items():
                macros.add(macro_name("Eone", "base", row, opponent, split), f"{entry['mean']:.3f}")
    for gap in paired["gaps"]:
        base = macro_name("Eone", "gap", gap["method"], gap["opponent"], gap["split"])
        macros.add(base, f"{gap['gap']:+.3f}")
        macros.add(base + "Lo", f"{gap['ci'][0]:+.3f}")
        macros.add(base + "Hi", f"{gap['ci'][1]:+.3f}")
    for test in paired["family"]:
        base = macro_name("Eone", test["id"], test["split"])
        macros.add(base + "Diff", f"{test['diff']:+.3f}")
        macros.add(base + "P", fmt_p(test["p_holm"]))

    rows = []
    for opponent, label in (("greedy", "contra Greedy"), ("prior", "contra prior ARES")):
        rows.append(f"\\multicolumn{{{len(splits) + 1}}}{{l}}{{\\textit{{Puntaje {label}}}}}\\\\")
        for method in paired["methods"]:
            cells = []
            for split in splits:
                entry = scores[method].get(split, {}).get(opponent)
                cells.append("--" if not entry else f"{entry['mean']:.3f} \\tiny{{$\\pm${(entry['pair_ci'][1] - entry['pair_ci'][0]) / 2:.3f}}}")
            rows.append(f"{METHOD_NAMES.get(method, method)} & " + " & ".join(cells) + " \\\\")
        for row in ("greedy", "prior", "random"):
            by_split = paired.get("baselines", {}).get(row, {})
            if not by_split or row == opponent:
                continue
            cells = [f"{by_split[s][opponent]['mean']:.3f}" if opponent in by_split.get(s, {}) else "--" for s in splits]
            rows.append(f"{BASELINE_NAMES[row]} & " + " & ".join(cells) + " \\\\")
        rows.append("\\midrule")
    table = ["\\begin{tabular}{l" + "c" * len(splits) + "}", "\\toprule",
             "Agente & " + " & ".join(SPLIT_NAMES[s] for s in splits) + " \\\\", "\\midrule", *rows[:-1],
             "\\bottomrule", "\\end{tabular}"]
    (out / "tab_e1.tex").write_text("\n".join(table) + "\n", encoding="utf-8")

    hyp = ["\\begin{tabular}{llcccc}", "\\toprule", "H & Contraste & Split & $\\Delta$ & IC 95\\% & $p_{\\mathrm{Holm}}$ \\\\",
           "\\midrule"]
    for test in paired["family"]:
        contrast = (f"{METHOD_NAMES.get(test['a'], test['a'])} $-$ 0.5" if test["b"] == "parity 0.5"
                    else f"{METHOD_NAMES.get(test['a'], test['a'])} $-$ {METHOD_NAMES.get(test['b'], test['b'])}")
        hyp.append(f"{test['id']} & {contrast} & {SPLIT_NAMES[test['split']]} & {test['diff']:+.3f} & "
                   f"[{test['ci'][0]:+.3f}, {test['ci'][1]:+.3f}] & {fmt_p(test['p_holm'])} \\\\")
    hyp += ["\\bottomrule", "\\end{tabular}"]
    (out / "tab_hyp.tex").write_text("\n".join(hyp) + "\n", encoding="utf-8")

    for name in ("learning_curves.png", "generalisation_gap.png", "transfer_vs_greedy.png"):
        source = run / "figures" / name
        if source.exists():
            shutil.copy2(source, figs / f"e1_{name}")


def e2_assets(run: Path, out: Path, figs: Path, macros: Macros) -> None:
    summary = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    rows = ["\\begin{tabular}{lccc}", "\\toprule", "Método (Emerald) & Celdas/episodio & Semillas & Mapas \\\\",
            "\\midrule"]
    for entry in summary["eval"]:
        if entry["game"] != "emerald":
            continue
        method = entry["method"]
        macros.add(macro_name("Etwo", method, "cells"), f"{entry['mean_over_seeds']:.1f}")
        macros.add(macro_name("Etwo", method, "cells", "sd"), f"{entry['std_over_seeds']:.1f}")
        maps = entry.get("maps_mean", float("nan"))
        rows.append(f"{NAV_METHODS.get(method, method)} & {entry['mean_over_seeds']:.1f} $\\pm$ {entry['std_over_seeds']:.1f} & "
                    f"{entry['seeds']} & {maps if isinstance(maps, str) else f'{float(maps):.2f}'} \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    (out / "tab_e2.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    macros.add("EtwoSeeds", str(max((int(entry["seeds"]) for entry in summary["eval"]), default=0)))
    for test in summary.get("tests", []):
        base = macro_name("Etwo", test["a"], "vs", test["b"])
        macros.add(base + "Diff", f"{test['mean_diff']:+.1f}")
        macros.add(base + "Lo", f"{test['ci95_low']:+.1f}")
        macros.add(base + "Hi", f"{test['ci95_high']:+.1f}")
    efficiency = summary.get("sample_efficiency", {})
    if "budget_env_steps" in efficiency:
        macros.add("EtwoBudget", f"{int(efficiency['budget_env_steps']):,}".replace(",", "\\,"))
    for method, info in efficiency.get("methods", {}).items():
        macros.add(macro_name("Etwo", method, "auc"), f"{info['auc_global_cells_mean_std'][0]:.0f}")
        reach = info.get("global_cells>=random_full_budget", {})
        values = reach.get("mean_std_of_reached")
        if values and values[0] is not None:
            macros.add(macro_name("Etwo", method, "reach"), f"{float(values[0]):,.0f}".replace(",", "\\,"))
    for name in ("train_global_cells.png", "eval_emerald_bars.png", "ae_reconstruction.png"):
        source = run / "figures" / name
        if source.exists():
            shutil.copy2(source, figs / f"e2_{name}")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--e1", type=Path, default=ROOT / "artifacts/ares_u/battle/final")
    parser.add_argument("--e2", type=Path, default=ROOT / "artifacts/ares_u/nav/final")
    parser.add_argument("--out", type=Path, default=ROOT / "informe")
    args = parser.parse_args(argv)
    generated, figs = args.out / "generated", args.out / "figs"
    generated.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    macros = Macros()
    if (args.e1 / "paired.json").exists():
        e1_assets(args.e1, generated, figs, macros)
    else:
        print(f"[skip] E1: {args.e1 / 'paired.json'} missing")
    if (args.e2 / "summary.json").exists():
        e2_assets(args.e2, generated, figs, macros)
    else:
        print(f"[skip] E2: {args.e2 / 'summary.json'} missing")
    (generated / "numbers.tex").write_text(macros.text(), encoding="utf-8")
    print(generated)


if __name__ == "__main__":
    main()
